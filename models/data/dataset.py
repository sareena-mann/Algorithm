"""
Unified PyTorch Dataset that blends two data buckets in every batch:
  Bucket A — real human DJ transitions (from a local audio directory)
  Bucket B — synthetic transitions generated by synthetic.py

Each item returns a dict:
  context_a    : (1, T_a)      float32 audio at 44100 Hz
  bridge       : (1, T_bridge) float32 audio at 44100 Hz
  context_b    : (1, T_b)      float32 audio at 44100 Hz
  conditioning : (COND_DIM,)   float32 conditioning vector
  source       : str           "real" | "synthetic"

─── Real data directory layout ───────────────────────────────────────────────

  data_dir/
    metadata.json
    transitions/
      transition_001.wav
      transition_002.wav
      ...

Each WAV file is a single self-contained clip recorded as:
  [← 15 sec Track A →][← bridge (variable) →][← 10 sec Track B →]

The dataset slices it automatically:
  context_a = first 15 seconds
  bridge    = everything in between
  context_b = last 10 seconds

metadata.json is a list of one entry per WAV file:
  [
    {
      "file":    "transition_001.wav",
      "bpm_a":   124,
      "bpm_b":   128,
      "key_a":   "8A",
      "key_b":   "9A",
      "genre_a": "house",
      "genre_b": "techno"
    },
    ...
  ]
"""

import json
import random
import torch
import torchaudio
from pathlib import Path
from torch.utils.data import Dataset

from .synthetic import SyntheticTransitionGenerator
from .constants import (
    SAMPLE_RATE, CONTEXT_A_SECS, CONTEXT_B_SECS,
    BRIDGE_SECS_MIN, BRIDGE_SECS_MAX,
    GENRES, N_GENRES, COND_DIM, build_conditioning,
)


class RealTransitionDataset(Dataset):
    """
    Loads single-clip WAV files of the form:
      [15s Track A | bridge | 10s Track B]
    with metadata from metadata.json.
    """

    def __init__(self, data_dir: str):
        self.data_dir    = Path(data_dir)
        self.transitions = self.data_dir / "transitions"
        metadata_path    = self.data_dir / "metadata.json"

        if not metadata_path.exists():
            raise FileNotFoundError(f"No metadata.json found in {data_dir}")
        if not self.transitions.exists():
            raise FileNotFoundError(f"No transitions/ folder found in {data_dir}")

        with open(metadata_path) as f:
            self.entries = json.load(f)

    def __len__(self) -> int:
        return len(self.entries)

    def __getitem__(self, idx: int) -> dict:
        e     = self.entries[idx]
        audio = _load(self.transitions / e["file"])

        T_a = int(CONTEXT_A_SECS * SAMPLE_RATE)
        T_b = int(CONTEXT_B_SECS * SAMPLE_RATE)

        context_a = audio[:, :T_a]       # first 15 seconds
        context_b = audio[:, -T_b:]      # last 10 seconds
        bridge    = audio[:, T_a:-T_b]   # everything in between

        cond = build_conditioning(
            e.get("bpm_a", 120), e.get("bpm_b", 120),
            e.get("key_a", ""),  e.get("key_b", ""),
            e.get("genre_a", ""), e.get("genre_b", ""),
        )

        return {
            "context_a":    context_a,
            "bridge":       bridge,
            "context_b":    context_b,
            "conditioning": cond,
            "source":       "real",
        }


class BlendedTransitionDataset(Dataset):
    """
    Blends real and synthetic pairs.
    real_ratio=0.5 → every other sample is synthetic (approximately).
    """

    def __init__(
        self,
        data_dir:   str | None = None,
        synth_n:    int        = 20000,
        real_ratio: float      = 0.5,
    ):
        self.synth  = SyntheticTransitionGenerator(n_pairs=synth_n)
        self.real   = RealTransitionDataset(data_dir) if data_dir else None
        self.ratio  = real_ratio if self.real else 0.0
        self._len   = synth_n if not self.real else synth_n + len(self.real)

    def __len__(self) -> int:
        return self._len

    def __getitem__(self, idx: int) -> dict:
        if self.real and random.random() < self.ratio:
            real_idx = random.randint(0, len(self.real) - 1)
            return self.real[real_idx]
        synth_idx = random.randint(0, len(self.synth) - 1)
        return self.synth[synth_idx]


# ── Audio helpers ──────────────────────────────────────────────────────────

def _load(path: Path) -> torch.Tensor:
    """Load any WAV file → mono float32 tensor at SAMPLE_RATE."""
    audio, sr = torchaudio.load(str(path))
    if audio.shape[0] > 1:
        audio = audio.mean(dim=0, keepdim=True)
    if sr != SAMPLE_RATE:
        audio = torchaudio.functional.resample(audio, sr, SAMPLE_RATE)
    return audio.clamp(-1, 1)


def _pad(audio: torch.Tensor, target: int) -> torch.Tensor:
    pad = target - audio.shape[1]
    return torch.nn.functional.pad(audio, (0, pad))
